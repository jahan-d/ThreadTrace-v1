    CONSTRAINT transformation_outputs_unit_check
        CHECK (unit IN ('KG', 'METER', 'PIECES')),

    CONSTRAINT fkmaqx7k3o8lryu02cqcgpvecef
        FOREIGN KEY (lot_id) REFERENCES garment_lots(id),

    CONSTRAINT fkkmoaaen9ices615535va7461d
