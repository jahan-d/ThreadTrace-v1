-- 1. Suppliers
CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR(255),
    contact_person VARCHAR(255),
    country VARCHAR(255),
    created_at TIMESTAMP(6),
    email VARCHAR(255),
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(255),
    updated_at TIMESTAMP(6)
);

-- 2. Garment Lots
CREATE TABLE garment_lots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) NOT NULL,
    description VARCHAR(500),
    lot_number VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    supplier_id BIGINT NOT NULL,
    quantity NUMERIC(19,4),
    unit VARCHAR(20),
    version BIGINT NOT NULL,

    CONSTRAINT ukhamh8j15b7k8t8vfl9f6hf978
        UNIQUE (lot_number),

    CONSTRAINT garment_lots_status_check
        CHECK (status IN (
            'RAW_MATERIAL',
            'IN_PRODUCTION',
            'QUALITY_CHECK',
            'COMPLETED',
            'ARCHIVED'
        )),

    CONSTRAINT garment_lots_unit_check
        CHECK (unit IN ('KG', 'METER', 'PIECES')),

    CONSTRAINT fkcpsvtei0mj9pu1ar436tirksd
        FOREIGN KEY (supplier_id) REFERENCES suppliers(id)
);

-- 3. Lot Events
CREATE TABLE lot_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(1000),
    event_type VARCHAR(40) NOT NULL,
    new_status VARCHAR(30),
    occurred_at TIMESTAMP(6) NOT NULL,
    performed_by VARCHAR(150) NOT NULL,
    previous_status VARCHAR(30),
    recorded_at TIMESTAMP(6) NOT NULL,
    garment_lot_id BIGINT NOT NULL,

    CONSTRAINT lot_events_event_type_check
        CHECK (event_type IN (
            'RECEIVED',
            'CUT',
            'SEW',
            'WASH',
            'DYE',
            'FINISH',
            'QUALITY_CHECK_PASSED',
            'QUALITY_CHECK_FAILED',
            'PACK',
            'SHIP',
            'TRANSFORMATION_INPUT',
            'TRANSFORMATION_OUTPUT',
            'ARCHIVE'
        )),

    CONSTRAINT lot_events_new_status_check
        CHECK (new_status IN (
            'RAW_MATERIAL',
            'IN_PRODUCTION',
            'QUALITY_CHECK',
            'COMPLETED',
            'ARCHIVED'
        )),

    CONSTRAINT lot_events_previous_status_check
        CHECK (previous_status IN (
            'RAW_MATERIAL',
            'IN_PRODUCTION',
            'QUALITY_CHECK',
            'COMPLETED',
            'ARCHIVED'
        )),

    CONSTRAINT fkl19650p43iayargnyyaj0wh8g
        FOREIGN KEY (garment_lot_id) REFERENCES garment_lots(id)
);

-- 4. Lot Transformations
CREATE TABLE lot_transformations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notes VARCHAR(1000),
    occurred_at TIMESTAMP(6) NOT NULL,
    performed_by VARCHAR(100) NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL,
    transformation_type VARCHAR(255) NOT NULL,
    waste_quantity NUMERIC(19,4) NOT NULL,
    waste_unit VARCHAR(255) NOT NULL,

    CONSTRAINT lot_transformations_transformation_type_check
        CHECK (transformation_type IN ('SPLIT', 'MERGE', 'PROCESS')),

    CONSTRAINT lot_transformations_waste_unit_check
        CHECK (waste_unit IN ('KG', 'METER', 'PIECES'))
);

-- 5. Transformation Inputs
CREATE TABLE transformation_inputs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity NUMERIC(19,4) NOT NULL,
    unit VARCHAR(255) NOT NULL,
    lot_id BIGINT NOT NULL,
    transformation_id BIGINT NOT NULL,

    CONSTRAINT transformation_inputs_unit_check
        CHECK (unit IN ('KG', 'METER', 'PIECES')),

    CONSTRAINT fk4no674qnf467ccxmgci2pxvdn
        FOREIGN KEY (lot_id) REFERENCES garment_lots(id),

    CONSTRAINT fkyhk46mhnaixndyjuor8v00pe
        FOREIGN KEY (transformation_id) REFERENCES lot_transformations(id)
);

